// Generates src/pdf/engine/encodings.generated.ts from pdfjs-dist (Apache-2.0):
// the standard PDF simple-font encodings and a filtered Adobe Glyph List.
// Re-run after upgrading pdfjs-dist:  node scripts/gen-pdf-encodings.cjs
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'node_modules/pdfjs-dist/build/pdf.worker.mjs'), 'utf8');

const grab = (name) => {
    const start = src.indexOf('const ' + name + ' = [');
    if (start < 0) throw new Error('missing ' + name);
    const open = src.indexOf('[', start);
    const close = src.indexOf('];', open);
    return JSON.parse(src.slice(open, close + 1));
};

const tableBlock = (fnName) => {
    const start = src.indexOf('const ' + fnName + ' = getLookupTableFactory(function (t) {');
    if (start < 0) throw new Error('missing ' + fnName);
    const end = src.indexOf('});', start);
    const map = {};
    const re = /t(?:\.([A-Za-z_]\w*)|\["([^"]+)"\]) = (0x[0-9a-fA-F]+);/g;
    for (const m of src.slice(start, end).matchAll(re)) map[m[1] || m[2]] = parseInt(m[3], 16);
    return map;
};

const encNames = ['StandardEncoding', 'MacRomanEncoding', 'WinAnsiEncoding', 'MacExpertEncoding', 'SymbolSetEncoding', 'ZapfDingbatsEncoding'];

const aglAll = tableBlock('getGlyphsUnicode');
const agl = {};
for (const [name, cp] of Object.entries(aglAll)) {
    // Latin/Greek/Cyrillic, punctuation, currency, letterlike, arrows, math, shapes, ligatures.
    if (cp < 0x0530 || (cp >= 0x2000 && cp < 0x2c00) || (cp >= 0xfb00 && cp <= 0xfb06)) agl[name] = cp;
}
const ding = tableBlock('getDingbatsGlyphsUnicode');

const pack = (obj) => Object.entries(obj).map(([k, v]) => `${k}:${v.toString(36)}`).join(' ');
const compactEnc = (arr) => JSON.stringify(arr).replace(/""/g, '0').replace(/"/g, "'");

let out = `/* eslint-disable */
// GENERATED by scripts/gen-pdf-encodings.cjs from pdfjs-dist (Apache-2.0). Do not edit by hand.
// Standard PDF simple-font encodings (code -> glyph name) and a filtered Adobe Glyph List.

type Enc = (string | 0)[];
`;
for (const n of encNames) out += `export const ${n}: Enc = ${compactEnc(grab(n))};\n`;
out += `
// name:codepoint(base36) pairs
const AGL_PACKED = '${pack(agl)}';
const DINGBATS_PACKED = '${pack(ding)}';

let agl: Map<string, number> | null = null;
let dingbats: Map<string, number> | null = null;
const unpack = (s: string) => {
    const m = new Map<string, number>();
    for (const pair of s.split(' ')) {
        const i = pair.lastIndexOf(':');
        m.set(pair.slice(0, i), parseInt(pair.slice(i + 1), 36));
    }
    return m;
};
export function glyphList(): Map<string, number> {
    return (agl ??= unpack(AGL_PACKED));
}
export function dingbatsGlyphList(): Map<string, number> {
    return (dingbats ??= unpack(DINGBATS_PACKED));
}
`;
const target = path.join(root, 'src/pdf/engine/encodings.generated.ts');
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(root, target)}: ${Object.keys(agl).length} glyph names, ${out.length} bytes`);
