// Off-camera look at the builder: screenshots + control names, nothing saved.
import { launch, session, login, sleep, APP } from './rec-lib.mjs';
const CARD = 'article:has(.group\\/ime-container)';
const browser = await launch();
const { page } = await session(browser, 'desktop');
await login(page);
await page.goto(APP + '/create-test', { waitUntil: 'load', timeout: 60000 });
await page.getByPlaceholder(/e\.g\. Class 10 Science/).waitFor({ timeout: 60000 });
await sleep(2500);
await page.screenshot({ path: 'capture/probe/b1-top.png' });
const row = page.getByText('Institution branding').first();
await row.scrollIntoViewIfNeeded(); await sleep(500);
await page.screenshot({ path: 'capture/probe/b2-row.png' });
await row.click(); await sleep(1200);
await page.screenshot({ path: 'capture/probe/b3-open.png' });
await page.locator('input[type=file][accept="image/*"]').first().setInputFiles('capture/paper/apex-academy-logo.png');
await sleep(1500);
await page.getByLabel('Institution name').fill('Apex Academy');
await page.getByLabel('Colour #2563eb').click();
await page.locator('select').filter({ has: page.locator('option[value="serif"]') }).selectOption("'Georgia', serif");
await sleep(800);
await page.screenshot({ path: 'capture/probe/b4-filled.png' });
const q = page.locator('#questions-heading');
await q.scrollIntoViewIfNeeded(); await sleep(800);
await page.screenshot({ path: 'capture/probe/b5-questions.png' });
console.log('cards', await page.locator(CARD).count());
console.log('buttons:', (await page.getByRole('button').filter({ visible: true }).allInnerTexts()).map((s) => s.trim().replace(/\s+/g, ' ')).filter(Boolean).join(' | '));
const a = page.locator(CARD).first();
console.log('card labels:', await a.evaluate((el) => [...el.querySelectorAll('[aria-label],[placeholder]')].map((e) => e.tagName + ':' + (e.getAttribute('aria-label') || e.getAttribute('placeholder'))).join(' | ')));
await browser.close();
